// check:file-size: the pure rules (token math, ignore globs, generated header, the message) and the real hook in a
// temporary git repository (it runs `git commit`, so the hook wiring itself is tested, not only the script).
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterAll, describe, expect, it } from 'vitest';
import { formatReport, hasGeneratedHeader, headerBytes, isIgnored, isOverLimit, looksBinary, parseIgnore, tokensOf } from './check-file-size.mjs';
import { HOOKS_DIR, installHooks } from './install-hooks.mjs';

const REPO = fileURLToPath(new URL('..', import.meta.url));
const real = (p) => readFileSync(join(REPO, p), 'utf8');
const rules = parseIgnore(real('.filesizeignore'));

describe('token math: bytes / 4, over 5,000 fails', () => {
  it('passes at exactly 20,000 bytes and fails at 20,001', () => {
    expect(isOverLimit(20_000)).toBe(false);
    expect(isOverLimit(20_001)).toBe(true);
    expect(isOverLimit(0)).toBe(false);
  });
  it('reports tokens rounded up to an integer', () => {
    expect(tokensOf(20_000)).toBe(5000);
    expect(tokensOf(20_001)).toBe(5001);
    expect(tokensOf(20_004)).toBe(5001);
    expect(tokensOf(20_005)).toBe(5002);
  });
});

describe('the ignore list', () => {
  it('skips lockfiles at the root and in a subdirectory', () => {
    for (const p of ['package-lock.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lockb', 'Cargo.lock', 'apps/web/package-lock.json', 'go.sum']) expect(isIgnored(p, rules), p).toBe(true);
  });
  it('skips generated output, build directories, source maps and SVG', () => {
    for (const p of ['src/api.generated.ts', 'src/schema.gen.ts', 'public/app.min.js', 'dist/index.js', 'a/b/dist/x.js', 'coverage/lcov.info', 'dev-dist/sw.js', '.vite/deps/x.js', 'node_modules/x/y.js', 'assets/app.js.map', 'public/favicon.svg', 'src/__snapshots__/a.snap', 'scripts/og/og-image.inputs.json']) expect(isIgnored(p, rules), p).toBe(true);
  });
  it('measures the files an agent writes', () => {
    for (const p of ['src/App.tsx', 'src/logic.test.ts', 'docs/architecture.md', 'AGENTS.md', 'e2e/drive.mjs', 'package.json', 'scripts/mutate.mjs', 'distribution/notes.md', 'src/dist.ts']) expect(isIgnored(p, rules), p).toBe(false);
  });
  it('reads gitignore-style lines: comments, anchors, directories, ** and negation', () => {
    const r = parseIgnore('# comment\n\n/only-root.txt\ndocs/*.json\nvendor/\n**/gen/**/*.ts\n*.log\n!keep.log\n');
    expect(isIgnored('only-root.txt', r)).toBe(true);
    expect(isIgnored('sub/only-root.txt', r)).toBe(false);
    expect(isIgnored('docs/a.json', r)).toBe(true);
    expect(isIgnored('docs/deep/a.json', r)).toBe(false);
    expect(isIgnored('vendor/x/y.js', r)).toBe(true);
    expect(isIgnored('vendor', r)).toBe(false);
    expect(isIgnored('a/gen/b/c.ts', r)).toBe(true);
    expect(isIgnored('gen/c.ts', r)).toBe(true);
    expect(isIgnored('x/run.log', r)).toBe(true);
    expect(isIgnored('x/keep.log', r)).toBe(false);
  });
});

describe('generated and binary detection', () => {
  it('finds @generated and DO NOT EDIT in the first lines only', () => {
    expect(hasGeneratedHeader('// @generated by codegen\nexport const a = 1;\n')).toBe(true);
    expect(hasGeneratedHeader('/* DO NOT EDIT. Written by tool. */\n')).toBe(true);
    expect(hasGeneratedHeader('line\n'.repeat(10) + '// @generated\n')).toBe(false);
    expect(hasGeneratedHeader('export const a = 1;\n')).toBe(false);
  });
  it('scans through the tenth newline, not the first 4,096 bytes', () => {
    const wide = `${'x'.repeat(5000)}\n`;
    const late = Buffer.from(`${wide}// @generated\n${'y'.repeat(100)}`);
    expect(hasGeneratedHeader(headerBytes(late).toString('utf8'))).toBe(true);
    const tenth = Buffer.from(`${wide.repeat(9)}// DO NOT EDIT\nrest\n`);
    expect(hasGeneratedHeader(headerBytes(tenth).toString('utf8'))).toBe(true);
    const eleventh = Buffer.from(`${wide.repeat(10)}// @generated\n`);
    expect(hasGeneratedHeader(headerBytes(eleventh).toString('utf8'))).toBe(false);
    expect(headerBytes(Buffer.from('a\nb')).toString()).toBe('a\nb');
  });
  it('treats a NUL byte as binary', () => {
    expect(looksBinary(Buffer.from([0x89, 0x50, 0x00, 0x47]))).toBe(true);
    expect(looksBinary(Buffer.from('plain text'))).toBe(false);
  });
});

describe('the message', () => {
  const msg = formatReport([{ path: 'src/App.tsx', bytes: 30_342 }, { path: 'src/logic.test.ts', bytes: 38_933 }, { path: 'docs/architecture.md', bytes: 34_908 }]);
  it('lists each file with its token count and the limit', () => {
    expect(msg).toContain('src/App.tsx');
    expect(msg).toContain('7,586 tokens');
    expect(msg).toContain('9,734 tokens');
    expect(msg).toContain('limit 5,000');
    expect(msg).toContain('3 staged files are over 5,000 tokens');
  });
  it('gives the split steps, with names built from the offending file', () => {
    expect(msg).toContain('src/App.tsx -> src/App/types.ts');
    expect(msg).toMatch(/MOVE the code/);
    expect(msg).toContain('re-exports');
    expect(msg).toContain('npm test and npm run build');
    expect(msg).toContain('npm run check');
    expect(msg).toContain('git add');
  });
  it('says how to split tests and docs, and what to do for a file no agent wrote', () => {
    expect(msg).toContain('split by describe block');
    expect(msg).toContain('src/logic.test.ts -> src/logic/<describe name>.test.ts');
    expect(msg).toContain('split by heading');
    expect(msg).toContain('.filesizeignore');
    expect(msg).toContain('--no-verify` is not the fix');
  });
  it('is readable: at most 25 lines, and no dashes', () => {
    expect(msg.split('\n').length).toBeLessThanOrEqual(25);
    const many = formatReport(Array.from({ length: 40 }, (_, i) => ({ path: `src/f${i}.ts`, bytes: 30_000 + i })));
    expect(many.split('\n').length).toBeLessThanOrEqual(25);
    expect(many).toContain('...and 35 more');
    expect(msg + many).not.toMatch(/[\u2013\u2014]/);
  });
  it('says "file is" for one file', () => {
    expect(formatReport([{ path: 'a.ts', bytes: 20_001 }])).toContain('1 staged file is over 5,000 tokens');
  });
});

describe('install-hooks (prepare)', () => {
  const run = (calls, answers = {}) => (args) => { calls.push(args.join(' ')); const a = answers[args[0] === 'config' && args.includes('--get') ? 'get' : args[0]]; if (a instanceof Error) throw a; return a ?? ''; };
  it('does nothing in CI', () => {
    const calls = [];
    expect(installHooks({ CI: 'true' }, run(calls))).toBe('skipped: CI');
    expect(calls).toEqual([]);
  });
  it('does nothing outside a git checkout, and never throws', () => {
    expect(installHooks({}, run([], { 'rev-parse': new Error('not a git repo') }))).toMatch(/^skipped: not a git checkout/);
  });
  it('does nothing below the top of a work tree', () => {
    expect(installHooks({}, run([], { 'rev-parse': 'sub/' }))).toBe('skipped: not the top of a git checkout');
  });
  it('sets core.hooksPath once, and leaves another value alone', () => {
    const calls = [];
    expect(installHooks({}, run(calls, { get: new Error('unset') }))).toBe(`set core.hooksPath to ${HOOKS_DIR}`);
    expect(calls.at(-1)).toBe(`config --local core.hooksPath ${HOOKS_DIR}`);
    expect(installHooks({}, run([], { get: HOOKS_DIR }))).toBe('already set');
    const other = [];
    expect(installHooks({}, run(other, { get: '.husky' }))).toBe('skipped: core.hooksPath is already .husky');
    expect(other.some((c) => c.startsWith('config --local core.hooksPath'))).toBe(false);
  });
  it('reads core.hooksPath from every config scope, so a global value is not overridden', () => {
    const calls = [];
    expect(installHooks({}, run(calls, { get: 'global-hooks' }))).toBe('skipped: core.hooksPath is already global-hooks');
    expect(calls).toContain('config --get core.hooksPath');
    expect(calls.some((c) => c.includes('--local'))).toBe(false);
  });
});

describe('the hook in a temporary git repository', () => {
  const dirs = [];
  afterAll(() => { for (const d of dirs) rmSync(d, { recursive: true, force: true }); });
  const env = { ...process.env, PATH: `${dirname(process.execPath)}:${process.env.PATH}`, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null' };
  const sh = (cwd, cmd, args) => spawnSync(cmd, args, { cwd, env, encoding: 'utf8' });
  const git = (cwd, ...args) => sh(cwd, 'git', args);
  const bytes = (n, ch = 'a') => `${(ch.repeat(79) + '\n').repeat(Math.floor(n / 80))}${ch.repeat(n % 80)}`; // exactly n bytes

  /** A repo with the real hook, script and ignore list, wired through core.hooksPath exactly as `npm ci` does. */
  function repo() {
    const dir = mkdtempSync(join(tmpdir(), 'check-file-size-'));
    dirs.push(dir);
    git(dir, 'init', '-q');
    git(dir, 'config', 'user.name', 'Test');
    git(dir, 'config', 'user.email', 'test@example.com');
    mkdirSync(join(dir, '.githooks'));
    mkdirSync(join(dir, 'scripts'));
    for (const f of ['.githooks/pre-commit', 'scripts/check-file-size.mjs', '.filesizeignore']) copyFileSync(join(REPO, f), join(dir, f));
    git(dir, 'config', 'core.hooksPath', '.githooks');
    return dir;
  }
  const put = (dir, path, text) => { mkdirSync(dirname(join(dir, path)), { recursive: true }); writeFileSync(join(dir, path), text); };
  const commit = (dir) => git(dir, 'commit', '-q', '-m', 'test');

  it('blocks a staged file of 20,001 bytes with exit 1 and the message', () => {
    const dir = repo();
    put(dir, 'src/big.ts', bytes(20_001));
    git(dir, 'add', 'src/big.ts');
    const r = commit(dir);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('src/big.ts');
    expect(r.stderr).toContain('5,001 tokens');
    expect(r.stderr).toContain('limit 5,000');
    expect(r.stderr).toContain('How to split');
    expect(git(dir, 'log', '--oneline').status).not.toBe(0); // nothing was committed
  });
  it('lets a staged file of exactly 20,000 bytes through', () => {
    const dir = repo();
    put(dir, 'src/edge.ts', bytes(20_000));
    git(dir, 'add', 'src/edge.ts');
    expect(commit(dir).status).toBe(0);
  });
  it('lets a lockfile of the same size through', () => {
    const dir = repo();
    put(dir, 'package-lock.json', bytes(30_000));
    put(dir, 'src/small.ts', 'export const a = 1;\n');
    git(dir, 'add', '.');
    expect(commit(dir).status).toBe(0);
  });
  it('lets only small files through', () => {
    const dir = repo();
    put(dir, 'src/small.ts', 'export const a = 1;\n');
    git(dir, 'add', 'src/small.ts');
    expect(commit(dir).status).toBe(0);
  });
  it('does not look at a big file that is not staged', () => {
    const dir = repo();
    put(dir, 'src/big.ts', bytes(30_000));
    put(dir, 'src/small.ts', 'export const a = 1;\n');
    git(dir, 'add', 'src/small.ts');
    expect(commit(dir).status).toBe(0);
  });
  it('measures a partly staged file as staged', () => {
    const dir = repo();
    put(dir, 'src/grow.ts', bytes(1000));
    git(dir, 'add', 'src/grow.ts');
    expect(commit(dir).status).toBe(0);
    put(dir, 'src/grow.ts', bytes(1500));
    git(dir, 'add', 'src/grow.ts');
    put(dir, 'src/grow.ts', bytes(30_000)); // unstaged edit on top of a small staged version
    expect(commit(dir).status).toBe(0);
    git(dir, 'add', 'src/grow.ts'); // now the big version is staged
    const r = commit(dir);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('7,500 tokens');
  });
  it('checks a renamed big file, and does not block deleting one', () => {
    const dir = repo();
    put(dir, 'src/old.ts', bytes(25_000));
    git(dir, 'add', '.');
    expect(git(dir, 'commit', '-q', '--no-verify', '-m', 'big, before the hook existed').status).toBe(0);
    git(dir, 'mv', 'src/old.ts', 'src/new.ts');
    const renamed = commit(dir);
    expect(renamed.status).toBe(1);
    expect(renamed.stderr).toContain('src/new.ts');
    git(dir, 'rm', '-q', '-f', 'src/new.ts');
    expect(commit(dir).status).toBe(0);
  });
  it('skips binary files, symlinks, generated headers and ignored paths', () => {
    const dir = repo();
    writeFileSync(join(dir, 'pic.bin'), Buffer.concat([Buffer.from([0, 1, 2]), Buffer.alloc(30_000, 7)]));
    symlinkSync('a'.repeat(100), join(dir, 'link'));
    put(dir, 'src/api.ts', `// @generated\n${bytes(30_000)}`);
    put(dir, 'src/tools.generated.ts', bytes(30_000));
    put(dir, 'src/wide.ts', `${'x'.repeat(5000)}\n// DO NOT EDIT\n${bytes(30_000)}`); // marker on line 2, past byte 4,096
    put(dir, 'public/icon.svg', bytes(30_000));
    git(dir, 'add', '.');
    const r = commit(dir);
    expect(r.stderr).toBe('');
    expect(r.status).toBe(0);
  });
  it('--all reports tracked files over the limit', () => {
    const dir = repo();
    put(dir, 'src/big.ts', bytes(24_000));
    git(dir, 'add', '.');
    const r = sh(dir, process.execPath, ['scripts/check-file-size.mjs', '--all']);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('check-file-size: report. 1 tracked file is over 5,000 tokens');
    expect(r.stderr).toContain('6,000 tokens  src/big.ts');
  });
  it('exits 2 outside a git repository', () => {
    const dir = mkdtempSync(join(tmpdir(), 'check-file-size-nogit-'));
    dirs.push(dir);
    const r = sh(dir, process.execPath, [join(REPO, 'scripts/check-file-size.mjs')]);
    expect(r.status).toBe(2);
  });
});
